

class Solution {
public:
    long long countCommas(long long n) {
        long long ans = 0;

        // 1 comma: 1,000 – 999,999
        if (n >= 1000)
            ans += min(n, 999999LL) - 999LL;

        // 2 commas: 1,000,000 – 999,999,999
        if (n >= 1000000)
            ans += 2 * (min(n, 999999999LL) - 999999LL);

        // 3 commas: 1,000,000,000 – 999,999,999,999
        if (n >= 1000000000)
            ans += 3 * (min(n, 999999999999LL) - 999999999LL);

        // 4 commas: 1,000,000,000,000 – 999,999,999,999,999
        if (n >= 1000000000000LL)
            ans += 4 * (min(n, 999999999999999LL) - 999999999999LL);

        // 5 commas: 1,000,000,000,000,000 – 999,999,999,999,999,999
        if (n >= 1000000000000000LL)
            ans += 5 * (min(n, 999999999999999999LL) - 999999999999999LL);

        return ans;
    }
};
